/* Fonts for C65TERM, built at start-up from the ROM's character sets:
**   font 0  CP437 (ANSI / VT100): ASCII from the C64 lower case set, box
**           drawing, blocks and shades drawn here, accented letters mapped
**           to their base letters
**   font 1  C64 upper case / graphics (PETSCII), straight from the ROM
**   font 2  C64 lower / upper case (PETSCII)
** All three live in bank 1 (see hw.s).
*/
#include "ascii.h"
#include "term.h"

#define ROMSET_UP  0x29000UL
#define ROMSET_LO  0x29800UL
#define FONTS      0x1C000UL

static unsigned char g[8];

static void put_glyph(unsigned char ch)
{
	unsigned char i;
	g_far = FONTS + (unsigned long)ch * 8;
	for (i = 0; i < 8; i++) { far_put(g[i]); ++g_far; }
}

static void rom_glyph(unsigned char sc)
{
	unsigned char i;
	g_far = ROMSET_LO + (unsigned long)sc * 8;
	for (i = 0; i < 8; i++) { g[i] = far_get(); ++g_far; }
}

