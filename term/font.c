/* CP437 $B3-$DA: line arms up, down, left, right (0 none, 1 single, 2 double) */
static const unsigned char box[40] = {
	/* B3 */ 0x50, 0x54, 0x58, 0xA4, 0x24, 0x18, 0xA8, 0xA0,
	/* BB */ 0x28, 0x88, 0x84, 0x48, 0x14, 0x41, 0x45, 0x15,
	/* C3 */ 0x51, 0x05, 0x55, 0x52, 0xA1, 0x82, 0x22, 0x8A,
	/* CB */ 0x2A, 0xA2, 0x0A, 0xAA, 0x4A, 0x85, 0x1A, 0x25,
	/* D3 */ 0x81, 0x42, 0x12, 0x21, 0xA5, 0x5A, 0x44, 0x11
};

static void draw_box(unsigned char code)
{
	unsigned char u, d, l, r, y;
	u = code >> 6; d = (code >> 4) & 3; l = (code >> 2) & 3; r = code & 3;
	for (y = 0; y < 8; y++) g[y] = 0;
	/* vertical arms: single at column 3, double at columns 2 and 5 */
	for (y = 0; y < 8; y++) {
		unsigned char a = (y <= 4) ? u : 0, b = (y >= 3) ? d : 0, m = a > b ? a : b;
		if (m == 1) g[y] |= 0x10;
		if (m == 2) g[y] |= 0x24;
	}
	/* horizontal arms: single on row 3, double on rows 2 and 5 */
	if (l == 1) g[3] |= 0xF8;
	if (r == 1) g[3] |= 0x1F;
	if (l == 2) { g[2] |= 0xFC; g[5] |= 0xFC; }
	if (r == 2) { g[2] |= 0x3F; g[5] |= 0x3F; }
}

/* CP437 $80-$AF and $E0-$EF: nearest ASCII letter */
static const char hi_map[] =
	"CueaaaaceeeiiiAAEaAooouuyOUcLYPf"   /* $80-$9F */
	"aiounNao?--24!<>";                  /* $A0-$AF */
static const char gr_map[] = "aBGpSsutFTOd8onE";   /* $E0-$EF */

static unsigned char ascii_sc(unsigned char c)
{
	if (c == '@') return 0;
	if (c >= 'A' && c <= 'Z') return c;           /* shifted = upper case */
	if (c >= 'a' && c <= 'z') return c - 0x60;
	if (c == '[') return 0x1B;
	if (c == ']') return 0x1D;
	return c;                                      /* $20-$3F */
}

void font_build(void)
{
	unsigned int i;
	unsigned char c, j;

	/* PETSCII fonts: copy the ROM sets */
	g_far = ROMSET_UP; g_copydst = FONTS + 0x800; hw_copy_far(0x800);
	g_far = ROMSET_LO; g_copydst = FONTS + 0x1000; hw_copy_far(0x800);

	/* CP437 */
	for (i = 0; i < 256; i++) {
		c = (unsigned char)i;
		for (j = 0; j < 8; j++) g[j] = 0;
		if (c >= 0x20 && c < 0x7F) rom_glyph(ascii_sc(c));
		else if (c >= 0x80 && c < 0xB0) rom_glyph(ascii_sc(hi_map[c - 0x80]));
		else if (c >= 0xE0 && c < 0xF0) rom_glyph(ascii_sc(gr_map[c - 0xE0]));
		else if (c >= 0xB3 && c <= 0xDA) draw_box(box[c - 0xB3]);
		put_glyph(c);
	}
	for (i = 0; i < sizeof(extra) / sizeof(extra[0]); i++) {
		for (j = 0; j < 8; j++) g[j] = extra[i][j + 1];
		put_glyph(extra[i][0]);
	}
}
