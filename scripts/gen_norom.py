COLS = max(len(line) for line in MESSAGE)
ROWS = len(MESSAGE)


def glyph_rows(ch):
    rows = FONT[ch]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    # 8x8 cell: 5x7 glyph, one blank column left and two right, blank last row
    return [int((" " + r + "  ").replace("#", "1").replace(" ", "0"), 2) for r in rows] + [0]


def main():
    chars = sorted({c for line in MESSAGE for c in line} | {" "})
    code = {c: i for i, c in enumerate(chars)}
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = []
    w = out.append
    w("// Generated by scripts/gen_norom.py: edit that, not this file.")
    w("//")
    w("// The \"no system ROM\" message: drawn over the video (the VIC runs alone,")
    w("// showing its reset border colour) while the core has no ROM to start.")
    w("// Characters are 8x8 cells shown at twice their size.")
    w("")
    w("module c65_norom (")
    w("\tinput  logic       clk,")
    w("\tinput  logic       ce_pix,     // one per pixel")
    w("\tinput  logic       hblank,")
    w("\tinput  logic       vblank,")
    w("\tinput  logic       enable,")
    w("\tinput  logic [7:0] r_in, g_in, b_in,")
    w("\toutput logic [7:0] r, g, b")
    w(");")
    w("")
    w(f"localparam COLS = {COLS}, ROWS = {ROWS};")
    w("localparam X0 = 48, Y0 = 64;     // top left corner of the text, in output pixels")
    w("")
    w("logic [10:0] px, py;")
    w("logic        hb_d;")
    w("always_ff @(posedge clk) begin")
    w("\tif (ce_pix) begin")
    w("\t\thb_d <= hblank;")
    w("\t\tif (hblank) px <= '0; else px <= px + 11'd1;")
    w("\t\tif (vblank) py <= '0;")
    w("\t\telse if (hblank && !hb_d) py <= py + 11'd1;")
    w("\tend")
    w("end")
    w("")
    w("// text position: each character cell is 16x16 output pixels")
    w("wire [10:0] tx = px - 11'(X0);")
    w("wire [10:0] ty = py - 11'(Y0);")
    w("wire        in_text = (px >= 11'(X0)) && (py >= 11'(Y0)) && (tx[10:4] < 7'(COLS)) && (ty[10:4] < 7'(ROWS));")
    w("")
    w("function automatic [5:0] char_at(input logic [3:0] row, input logic [5:0] col);")
    w("\tcase ({row, col})")
    for ri, line in enumerate(MESSAGE):
        for ci, ch in enumerate(line):
            if ch != " ":
                w(f"\t\t{{4'd{ri}, 6'd{ci}}}: char_at = 6'd{code[ch]};   // {ch}")
    w(f"\t\tdefault: char_at = 6'd{code[' ']};")
    w("\tendcase")
    w("endfunction")
    w("")
    w("function automatic [7:0] glyph(input logic [5:0] c, input logic [2:0] y);")
    w("\tcase ({c, y})")
    for ch in chars:
        for y, bits in enumerate(glyph_rows(ch)):
            if bits:
                w(f"\t\t{{6'd{code[ch]}, 3'd{y}}}: glyph = 8'h{bits:02X};   // {ch}")
    w("\t\tdefault: glyph = 8'h00;")
    w("\tendcase")
    w("endfunction")
    w("")
    w("// one pipeline stage: look the pixel up, then mix it in")
    w("logic       dot;")
    w("logic [7:0] r_d, g_d, b_d;")
    w("always_ff @(posedge clk) begin")
    w("\tlogic [7:0] row;")
    w("\trow = glyph(char_at(ty[7:4], tx[9:4]), ty[3:1]);")
    w("\tdot <= enable && in_text && row[3'd7 - tx[3:1]];")
    w("\tr_d <= r_in; g_d <= g_in; b_d <= b_in;")
    w("end")
    w("")
    w("assign r = dot ? 8'hFF : r_d;")
    w("assign g = dot ? 8'hFF : g_d;")
    w("assign b = dot ? 8'hFF : b_d;")
    w("")
    w("endmodule")
    with open(os.path.join(root, "rtl", "c65_norom.sv"), "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote rtl/c65_norom.sv:", ROWS, "rows,", COLS, "cols,", len(chars), "characters")


if __name__ == "__main__":
    main()
