#!/usr/bin/env python3
"""Generate the 4510 opcode tables (SystemVerilog include + Python module).

The opcode -> (instruction, addressing mode) map is read from the MEGA65
gs4510.vhdl "4502 personality" lookup tables so it is not hand-transcribed.

usage: gen_cpu_tables.py <path/to/gs4510.vhdl>
"""
import re, sys, os

src = open(sys.argv[1], encoding="latin-1").read()

def grab(name):
    m = re.search(r"constant %s\s*:.*?:=\s*\((.*?)\);" % name, src, re.S)
    body = re.sub(r"--[^\n]*", "", m.group(1))
    return re.findall(r"[IM]_\w+", body)[:256]

ins = [i[2:] for i in grab("instruction_lut")]
mode = [m[2:] for m in grab("mode_lut")]
assert len(ins) == 256 and len(mode) == 256

MODEMAP = {"impl": "IMPL", "A": "IMPL", "immnn": "IMM", "immnnnn": "IMM16",
           "nn": "ZP", "nnX": "ZPX", "nnY": "ZPY", "nnnn": "ABS",
           "nnnnX": "ABSX", "nnnnY": "ABSY", "InnX": "INDX", "InnY": "INDY",
           "InnZ": "INDZ", "InnSPY": "INDSPY", "rr": "REL", "rrrr": "REL16",
           "nnrr": "ZPREL", "Innnn": "IND16", "InnnnX": "IND16X"}
mode = [MODEMAP[m] for m in mode]
mode[0x63] = "REL16"            # BSR is 16-bit relative
ins[0xEA] = "EOM"

inames = sorted(set(ins))
mnames = ["IMPL", "IMM", "IMM16", "ZP", "ZPX", "ZPY", "ABS", "ABSX", "ABSY",
          "INDX", "INDY", "INDZ", "INDSPY", "REL", "REL16", "ZPREL", "IND16",
          "IND16X"]

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
with open(os.path.join(root, "rtl", "cpu", "cpu4510_tables.svh"), "w", newline="\n") as f:
    f.write("// GENERATED by scripts/gen_cpu_tables.py from MEGA65 gs4510.vhdl -- do not edit\n")
    f.write("typedef enum logic [6:0] {\n  " + ",\n  ".join("I_" + n for n in inames) + "\n} ins_t;\n\n")
    f.write("typedef enum logic [4:0] {\n  " + ",\n  ".join("M_" + n for n in mnames) + "\n} mode_t;\n\n")
    f.write("function automatic ins_t ins_lut(input logic [7:0] op);\n  case (op)\n")
    for i in range(256):
        f.write("    8'h%02X: ins_lut = I_%s;\n" % (i, ins[i]))
    f.write("  endcase\nendfunction\n\n")
    f.write("function automatic mode_t mode_lut(input logic [7:0] op);\n  case (op)\n")
    for i in range(256):
        f.write("    8'h%02X: mode_lut = M_%s;\n" % (i, mode[i]))
    f.write("  endcase\nendfunction\n")

with open(os.path.join(root, "sim", "ref", "tables4510.py"), "w", newline="\n") as f:
    f.write("# GENERATED by scripts/gen_cpu_tables.py -- do not edit\n")
    f.write("INS = %r\n" % ins)
    f.write("MODE = %r\n" % mode)
print(len(inames), "instructions")
